CREATE TABLE account (
    account_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number  CHAR(12)      NOT NULL UNIQUE,
    currency_code   CHAR(3)       NOT NULL,
    balance         NUMBER(19,4)  NOT NULL,
    status          VARCHAR2(20)  NOT NULL,
    CONSTRAINT ck_account_balance CHECK (balance >= 0),
    CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED'))
);

CREATE TABLE ledger_entry (
    ledger_entry_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      NUMBER NOT NULL REFERENCES account(account_id),
    entry_type      VARCHAR2(6) NOT NULL,
    amount          NUMBER(19,4) NOT NULL,
    occurred_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_ledger_type CHECK (entry_type IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_amount CHECK (amount <> 0)
);


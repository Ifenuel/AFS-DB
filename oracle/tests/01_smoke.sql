-- Atomic transfer example. In a real procedure, lock both accounts in a
-- deterministic order with SELECT ... FOR UPDATE and validate status/balance.
SAVEPOINT before_transfer;
UPDATE account SET balance = balance - 100 WHERE account_number = 'ACC999999991';
UPDATE account SET balance = balance + 100 WHERE account_number = 'ACC999999992';
INSERT INTO ledger_entry (account_id, entry_type, amount)
SELECT account_id, 'DEBIT', -100 FROM account WHERE account_number = 'ACC999999991';
INSERT INTO ledger_entry (account_id, entry_type, amount)
SELECT account_id, 'CREDIT', 100 FROM account WHERE account_number = 'ACC999999992';
COMMIT;

SELECT a.account_number, a.balance, SUM(l.amount) AS ledger_sum
FROM account a
LEFT JOIN ledger_entry l ON l.account_id = a.account_id
GROUP BY a.account_number, a.balance
ORDER BY a.account_number;


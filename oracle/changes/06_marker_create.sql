-- AFS-DBA-001 | ORCL-CHG-001 step 3: create a known row so recovery is provable
ALTER SESSION SET CONTAINER = FREEPDB1;
SET PAGESIZE 100
SET LINESIZE 160

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE AFS_LAB.RECOVERY_MARKER PURGE';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE AFS_LAB.RECOVERY_MARKER (
  id        NUMBER(10)   PRIMARY KEY,
  note      VARCHAR2(80),
  created   TIMESTAMP    DEFAULT SYSTIMESTAMP
);

INSERT INTO AFS_LAB.RECOVERY_MARKER (id, note) VALUES (1, 'survives point-in-time recovery');
COMMIT;

ALTER SYSTEM SWITCH LOGFILE;

SELECT TO_CHAR(SYSDATE,'YYYY-MM-DD HH24:MI:SS') AS marker_time FROM dual;
SELECT COUNT(*) AS rows_now FROM AFS_LAB.RECOVERY_MARKER;

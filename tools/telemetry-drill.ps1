# Operational telemetry drill.
#
# Starts a Modbus TCP plant simulator, collects its three registers at 1 Hz into
# the historian, kills the simulator mid-run so coverage genuinely breaks, then
# restarts it. The evidence shows readings per tag, the gap that was recorded
# rather than silently lost, and the sampling interval that was actually achieved.
param(
    [string]$Evidence = 'evidence\verify\live\61_telemetry.txt',
    [int]$PlcPort = 15020,
    [int]$CollectSeconds = 70,
    [int]$OutageSeconds = 7
)

$ErrorActionPreference = 'Stop'
$repo = (Get-Location).Path
$work = 'C:\Backups\ha'
New-Item -ItemType Directory -Force -Path $work | Out-Null
$lines = New-Object System.Collections.Generic.List[string]
$progress = 'C:\Backups\ha\telemetry_drill_progress.log'
Set-Content -Path $progress -Value '' -Encoding utf8
function L([string]$m) {
    $lines.Add($m)
    Write-Host $m
    Add-Content -Path $progress -Value $m -Encoding utf8
}

$sqlcmd = 'C:\Program Files\Microsoft SQL Server\Client SDK\ODBC\180\Tools\Binn\SQLCMD.EXE'
if (-not (Test-Path $sqlcmd)) { $sqlcmd = 'sqlcmd' }

function New-Conn([string]$database) {
    $cs = "Server=.;Database=$database;Integrated Security=True;Encrypt=False;Connect Timeout=5;Application Name=AFS-TelemetryDrill"
    return New-Object System.Data.SqlClient.SqlConnection($cs)
}
function Table([string]$sql) {
    $c = New-Conn 'AFS_Archive'
    try {
        $c.Open()
        $cmd = $c.CreateCommand()
        $cmd.CommandText = $sql
        $cmd.CommandTimeout = 60
        $table = New-Object System.Data.DataTable
        $table.Load($cmd.ExecuteReader())
        return ,$table   # the comma stops PowerShell unrolling the rows
    } finally { $c.Dispose() }
}

L "=== Operational telemetry  $((Get-Date).ToString('s')) ==="
& $sqlcmd -S . -E -C -b -i (Join-Path $repo 'sql-server\tables\06_create_historian.sql') 2>&1 | ForEach-Object { L "schema            $_" }
L ''

$busy = Get-NetTCPConnection -LocalPort $PlcPort -State Listen -ErrorAction SilentlyContinue
if ($busy) { throw "port $PlcPort is already in use (pid $($busy.OwningProcess -join ', ')); refusing to test against a stale simulator" }

$simScript = Join-Path $repo 'tools\ot\plc_sim.py'
$simOut = Join-Path $work 'plc_sim.out'
$simErr = Join-Path $work 'plc_sim.err'
$simArgs = "`"$simScript`" --host 127.0.0.1 --port $PlcPort"
$sim = Start-Process python -ArgumentList $simArgs -PassThru -WindowStyle Hidden -RedirectStandardOutput $simOut -RedirectStandardError $simErr
Start-Sleep -Seconds 2
L "plant simulator   : tools\ot\plc_sim.py, pid $($sim.Id), 127.0.0.1:$PlcPort"
L "registers         : 0 wellhead pressure (bar), 1 separator flow (m3/h), 2 separator temperature (C)"
L "values            : synthetic, generated by the simulator; the Modbus exchange and the database write are real"
L ''

$collector = Join-Path $repo 'tools\ot\collector.ps1'
$collectLog = Join-Path $work 'telemetry_collector.log'
$collectArgs = "-NoProfile -ExecutionPolicy Bypass -File `"$collector`" -RunSeconds $CollectSeconds -IntervalMs 1000 -PlcPort $PlcPort -Log `"$collectLog`""
$col = Start-Process powershell -ArgumentList $collectArgs -PassThru -WindowStyle Hidden -RedirectStandardOutput (Join-Path $work 'collector.out') -RedirectStandardError (Join-Path $work 'collector.err')
L "collector         : tools\ot\collector.ps1, pid $($col.Id), 1 Hz for $CollectSeconds s"
Start-Sleep -Seconds 25

$stopped = Get-Date
Stop-Process -Id $sim.Id -Force
L ("plant stopped     : {0:HH:mm:ss.fff}  simulator killed, no readings possible" -f $stopped)
Start-Sleep -Seconds $OutageSeconds
$restarted = Get-Date
$sim = Start-Process python -ArgumentList $simArgs -PassThru -WindowStyle Hidden -RedirectStandardOutput $simOut -RedirectStandardError $simErr
L ("plant restarted   : {0:HH:mm:ss.fff}  simulator pid $($sim.Id) after {1:N1} s of outage" -f $restarted, $OutageSeconds)
L ''

if (-not $col.WaitForExit(($CollectSeconds + 40) * 1000)) { throw 'collector did not finish' }
L '--- collector log ---'
(Get-Content $collectLog -Raw).Trim().Split("`n") | ForEach-Object { L $_.TrimEnd() }
L ''

$runs = Table 'SELECT TOP 1 RunId, StartedAt, EndedAt, IntervalMs, ReadingsWritten, GapsDetected, Notes FROM telemetry.CollectorRun ORDER BY RunId DESC'
$run = $runs.Rows[0]
$runId = [int]$run['RunId']
L "--- run $runId in the historian ---"
L ("run window        : {0:HH:mm:ss.fff} to {1:HH:mm:ss.fff} UTC" -f ([datetime]$run['StartedAt']), ([datetime]$run['EndedAt']))
L "readings written  : $($run['ReadingsWritten']) rows at $($run['IntervalMs']) ms"
L "gaps recorded     : $($run['GapsDetected'])"
L ''

L '--- readings per tag ---'
$perTag = Table "SELECT t.TagCode, t.Unit, COUNT(*) AS n, MIN(r.Value) AS lo, MAX(r.Value) AS hi FROM telemetry.Reading r JOIN telemetry.Tag t ON t.TagId = r.TagId WHERE r.ObservedAt >= '$($run['StartedAt'].ToString('s'))' GROUP BY t.TagCode, t.Unit ORDER BY t.TagCode"
foreach ($r in $perTag.Rows) {
    L ("  {0,-14} {1,5} readings   {2,8:N2} to {3,8:N2} {4}" -f $r['TagCode'], $r['n'], $r['lo'], $r['hi'], $r['Unit'])
}
L ''

L '--- gap recorded while the plant was down ---'
$gaps = Table "SELECT GapStart, GapEnd, DATEDIFF(millisecond, GapStart, GapEnd) / 1000.0 AS seconds, MissedReadings FROM telemetry.Gap WHERE RunId = $runId ORDER BY GapId"
if ($gaps.Rows.Count -eq 0) { L '  none' }
foreach ($g in $gaps.Rows) {
    L ("  {0:HH:mm:ss.fff} to {1:HH:mm:ss.fff}  {2:N1} s  {3} missed samples" -f ([datetime]$g['GapStart']), ([datetime]$g['GapEnd']), $g['seconds'], $g['MissedReadings'])
}
L ''

L '--- sampling interval actually achieved (gap excluded) ---'
$spacing = Table @"
WITH x AS (
    SELECT TagId, ObservedAt,
           LAG(ObservedAt) OVER (PARTITION BY TagId ORDER BY ObservedAt) AS prev
    FROM telemetry.Reading
    WHERE ObservedAt >= '$($run['StartedAt'].ToString('s'))'
)
SELECT COUNT(*) AS intervals,
       MIN(DATEDIFF(millisecond, prev, ObservedAt)) AS min_ms,
       AVG(DATEDIFF(millisecond, prev, ObservedAt)) AS avg_ms,
       MAX(DATEDIFF(millisecond, prev, ObservedAt)) AS max_ms
FROM x
WHERE prev IS NOT NULL AND DATEDIFF(millisecond, prev, ObservedAt) < 5000;
"@
$sp = $spacing.Rows[0]
L ("  {0} intervals, min {1} ms, average {2:N0} ms, max {3} ms" -f $sp['intervals'], $sp['min_ms'], $sp['avg_ms'], $sp['max_ms'])
L ''

$retention = Table "SELECT COUNT(*) AS rows_now FROM telemetry.Reading"
L "historian size    : $($retention.Rows[0]['rows_now']) readings retained in AFS_Archive.telemetry.Reading"
L 'the archive database already enforces retention, so time-series data lives where its policy already applies.'

if (-not $sim.HasExited) { Stop-Process -Id $sim.Id -Force }

$dir = Split-Path -Parent $Evidence
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
Set-Content -Path $Evidence -Value ($lines -join "`r`n") -Encoding utf8
Write-Host "evidence written to $Evidence"
